#!/usr/bin/env python3
"""
dnshub-privacy - local encrypted DNS front: DoT on :853 and DoH on :443.

Purpose: the last leg. LAN/Wi-Fi sniffers and the VPN path itself can see
plain DNS unless the *device-to-box* hop is encrypted. This service terminates
TLS (a CA the user controls, generated by `dnshub install`) and forwards the
wire query to the dnshub resolver on 127.0.0.1:53 and nothing else. There is
no other upstream here, so the "encrypted all the way" property is enforced
by construction: no plaintext fallback exists in this file.

Routes (DoH):
  GET/POST /dns-query   application/dns-message -> resolver
  GET /ca.pem           install this CA once on each device
  GET /                 tiny setup page

DoT is a 2-byte length-prefixed DNS-over-TLS stream with ALPN "dot",
compatible with Android Private DNS, iOS profiles, stubby, kdig, etc.
"""
from __future__ import annotations

import asyncio
import base64
import contextlib
import os
import socket
import ssl
import struct
import sys
import time
import urllib.parse
from pathlib import Path

CERT = Path(os.environ.get("DNSHUB_PRIV_CERT", "/etc/dnshub/certs/server.crt"))
KEY = Path(os.environ.get("DNSHUB_PRIV_KEY", "/etc/dnshub/certs/server.key"))
CA = Path(os.environ.get("DNSHUB_PRIV_CA", "/etc/dnshub/certs/ca.crt"))
RESOLVER = (os.environ.get("DNSHUB_PRIV_UPSTREAM", "127.0.0.1"), 53)
QUERY_BUDGET = float(os.environ.get("DNSHUB_PRIV_TIMEOUT", "4"))
MAX_DNS = 4096  # largest single DNS message we accept (EDNS0 stays well under)

_conns = 0


def log(msg: str) -> None:
    sys.stdout.write(f"[{time.strftime('%H:%M:%S')}] privacy: {msg}\n")
    sys.stdout.flush()


# --- resolver hop -----------------------------------------------------------
def _udp_query(wire: bytes) -> bytes | None:
    """One shot at the local resolver over UDP. Blocking, short, called from
    the executor so the event loop is never held."""
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    s.settimeout(QUERY_BUDGET)
    try:
        s.sendto(wire, RESOLVER)
        data, _ = s.recvfrom(65535)
        return data
    except OSError:
        return None
    finally:
        s.close()


async def forward(wire: bytes) -> bytes | None:
    loop = asyncio.get_event_loop()
    return await loop.run_in_executor(None, _udp_query, wire)


def servfail(wire: bytes) -> bytes:
    """Minimal SERVFAIL that reuses the client's id and question when safe."""
    try:
        import dns.message
        q = dns.message.from_wire(wire, ignore_trailing=True)
        r = dns.message.make_response(q)
        r.set_rcode(dns.rcode.SERVFAIL)
        return r.to_wire()
    except Exception:
        # can't parse the question: a bare header-only SERVFAIL still lets a
        # client see the failure instead of hanging.
        return b"\x00\x00" + struct.pack(">H", 2) + b"\x00\x00\x00\x00\x00\x00"


def _check_certs() -> str | None:
    for p in (CERT, KEY, CA):
        if not p.is_file():
            return f"missing {p} (run `sudo dnshub install` to generate certs)"
    return None


def ssl_ctx(proto: str) -> ssl.SSLContext:
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    ctx.load_cert_chain(CERT, KEY)
    ctx.set_alpn_protocols([proto])
    ctx.minimum_version = ssl.TLSVersion.TLSv1_2
    return ctx


# --- DoT (RFC 7858) ----------------------------------------------------------
async def handle_dot(reader, writer) -> None:
    global _conns
    peer = writer.get_extra_info("peername")
    peer = peer[0] if peer else "?"
    _conns += 1
    with contextlib.suppress(Exception):
        not_al = (writer.get_extra_info("ssl_object").selected_alpn_protocol()
                  or "none")
        log(f"dot: {peer} connected (alpn={not_al})")
    try:
        while True:
            hdr = await reader.readexactly(2)
            (ln,) = struct.unpack(">H", hdr)
            if ln == 0 or ln > MAX_DNS:
                break
            wire = await reader.readexactly(ln)
            resp = await forward(wire)
            if resp is None:
                resp = servfail(wire)
                log(f"dot: resolver unreachable for {peer}, sent SERVFAIL")
            # mirror the response id to the client's request id if the resolver
            # changed it (it cannot - 127.0.0.1 echoes - but be defensive)
            writer.write(struct.pack(">H", len(resp)) + resp)
            await writer.drain()
    except (asyncio.IncompleteReadError, ConnectionResetError, BrokenPipeError,
            TimeoutError):
        pass
    except asyncio.CancelledError:
        pass
    except Exception as exc:
        log(f"dot: {peer} error: {type(exc).__name__}: {exc}")
    finally:
        with contextlib.suppress(Exception):
            writer.close()
            await writer.wait_closed()


# --- DoH (RFC 8484) ----------------------------------------------------------
async def _respond(writer, status, ctype, body: bytes) -> None:
    head = (f"HTTP/1.1 {status}\r\n"
            f"Content-Type: {ctype}\r\n"
            f"Content-Length: {len(body)}\r\n"
            f"Connection: close\r\n"
            f"Cache-Control: no-store\r\n\r\n")
    writer.write(head.encode() + body)
    await writer.drain()


