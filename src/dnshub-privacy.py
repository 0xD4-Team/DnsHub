async def handle_doh(reader, writer) -> None:
    peer = writer.get_extra_info("peername")
    peer = peer[0] if peer else "?"
    try:
        head = b""
        while b"\r\n\r\n" not in head and len(head) < 16384:
            chunk = await reader.read(4096)
            if not chunk:
                break
            head += chunk
        if b"\r\n\r\n" not in head:
            await _respond(writer, "400 Bad Request", "text/plain", b"bad request\n")
            return
        raw, _, rest = head.partition(b"\r\n\r\n")
        try:
            head_txt = raw.decode("ascii", "replace")
            req_line, *hlines = head_txt.split("\r\n")
            method, target, _ = req_line.split(" ", 2)
        except ValueError:
            await _respond(writer, "400 Bad Request", "text/plain", b"bad request\n")
            return
        headers = {}
        for h in hlines:
            if ":" in h:
                k, v = h.split(":", 1)
                headers[k.strip().lower()] = v.strip()

        if "expect" in headers and "100-continue" in headers["expect"].lower():
            writer.write(b"HTTP/1.1 100 Continue\r\n\r\n")
            await writer.drain()
            rest = b""

        parsed = urllib.parse.urlsplit(target)
        path = parsed.path
        if path == "/ca.pem" and method == "GET":
            body = CA.read_bytes()
            await _respond(writer, "200 OK", "application/x-pem-file", body)
            return
        if path == "/" and method == "GET":
            body = PAGE.encode()
            await _respond(writer, "200 OK", "text/html; charset=utf-8", body)
            return
        if path != "/dns-query":
            await _respond(writer, "404 Not Found", "text/plain", b"not found\n")
            return

        wire = b""
        if method == "GET":
            q = urllib.parse.parse_qs(parsed.query)
            enc = (q.get("dns") or [""])[0]
            if enc:
                enc += "=" * (-len(enc) % 4)
                with contextlib.suppress(Exception):
                    wire = base64.urlsafe_b64decode(enc)
        elif method == "POST":
            try:
                ln = int(headers.get("content-length", "0") or "0")
            except ValueError:
                ln = 0
            if ln > MAX_DNS:
                await _respond(writer, "413 Payload Too Large", "text/plain",
                               b"too large\n")
                return
            wire = rest
            while len(wire) < ln:
                chunk = await reader.read(min(4096, ln - len(wire)))
                if not chunk:
                    break
                wire += chunk

        if not wire:
            await _respond(writer, "400 Bad Request", "text/plain", b"empty query\n")
            return
        resp = await forward(wire)
        if resp is None:
            log(f"doh: resolver unreachable for {peer}")
            await _respond(writer, "502 Bad Gateway", "text/plain",
                           b"resolver down\n")
            return
        # honour the wire:id of the *client's* message if the resolver changed
        # it; RFC 8484 wants the response id preserved.
        await _respond(writer, "200 OK", "application/dns-message", resp)
    except (asyncio.CancelledError, ConnectionResetError):
        pass
    except Exception as exc:
        log(f"doh: {peer} error: {type(exc).__name__}: {exc}")
        with contextlib.suppress(Exception):
            await _respond(writer, "500 Internal Server Error", "text/plain",
                           b"error\n")
    finally:
        with contextlib.suppress(Exception):
            writer.close()
            await writer.wait_closed()


async def main() -> int:
    err = _check_certs()
    if err:
        log(err)
        return 1
    dot_ctx = ssl_ctx("dot")
    doh_ctx = ssl_ctx("http/1.1")
    d1 = await asyncio.start_server(handle_dot, "0.0.0.0", 853, ssl=dot_ctx)
    d2 = await asyncio.start_server(handle_doh, "0.0.0.0", 443, ssl=doh_ctx)
    log(f"dot :853  doh :443  upstream={RESOLVER[0]}:{RESOLVER[1]}")
    async with d1, d2:
        await asyncio.gather(d1.serve_forever(), d2.serve_forever())
    return 0


if __name__ == "__main__":
    try:
        sys.exit(asyncio.run(main()))
    except KeyboardInterrupt:
        sys.exit(130)